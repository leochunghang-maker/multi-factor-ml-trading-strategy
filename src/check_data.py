"""Check data freshness, alignment and quality; maintain the data manifest.

Read-only for data files. Examples:

    python src/check_data.py                       # print findings, exit 1 on ERROR
    python src/check_data.py --write-report        # also write reports/data_quality_report.md
    python src/check_data.py --as-of 2026-11-02    # evaluate freshness as of a date
    python src/check_data.py --update-manifest     # record current hashes (after review)
    python src/check_data.py --paper               # same checks on the paper data dir (data/paper/)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[1]))

from src.config import LOCAL_DATA_QUALITY_REPORT_PATH  # noqa: E402
from src.data.paths import DataPaths  # noqa: E402
from src.data.quality import (  # noqa: E402
    SEVERITIES,
    build_manifest,
    checkout_findings,
    data_check_settings,
    overall_status,
    paper_manifest_settings,
    run_data_checks,
)


def render_report(findings, summary, settings, *, checkout: bool = False) -> str:
    """Render the markdown report.

    ``checkout=True`` is the committed ``reports/data_quality_report.md``: wall-clock
    lag (last closed session, trading-day gap) is omitted so regenerating the report
    does not change the file when the frozen research snapshot is unchanged.
    ``checkout=False`` is the local or paper report and includes that lag.
    """
    shown = checkout_findings(findings) if checkout else list(findings)
    counts = {s: sum(f.severity == s for f in shown) for s in SEVERITIES}
    header_extra: list[str] = []
    if summary.get("freshness_reference") == "research_snapshot_end":
        if checkout:
            header_extra.append(
                "The research snapshot is frozen (`data_checks.research_snapshot_end`), so freshness is "
                "measured against its last session. The gap to the last closed NYSE session is written to "
                f"`{LOCAL_DATA_QUALITY_REPORT_PATH}` (gitignored) and printed by this command."
            )
        else:
            header_extra.append(
                "The research snapshot is frozen (`data_checks.research_snapshot_end`), so freshness is "
                "measured against its last session; the last closed NYSE session was "
                f"{summary.get('last_closed_session')}."
            )
    lines = [
        "# Data Quality Report",
        "",
        "Generated by `python src/check_data.py --write-report` (read-only; no data file is modified).",
        f"Freshness is evaluated as of **{summary['as_of']}** on the **{summary.get('calendar', 'NYSE')}** "
        "trading calendar (weekends and exchange holidays are not counted); re-run to refresh.",
        *header_extra,
        "",
        f"- Overall status: **{overall_status(shown)}**",
        f"- Findings: {counts['ERROR']} ERROR, {counts['WARNING']} WARNING, "
        f"{counts['INFO']} INFO",
        f"- Thresholds: stale > {settings['max_stale_trading_days']} trading days "
        f"({settings['stale_severity']}); date-range misalignment > {settings['max_end_date_gap_trading_days']} "
        f"trading days ({settings['misalignment_severity']}); calendar gap > {settings['max_calendar_gap_days']} "
        f"days; flat run ≥ {settings['flat_run_min_days']} identical closes; split-like jump ≥ "
        f"{settings['split_move_threshold']:.0%} with price ratio within {settings['split_ratio_tolerance']:.0%} "
        f"of a common split factor; large moves ≥ {settings['large_move_threshold']:.0%} listed as INFO.",
        "",
        "## Inputs",
        "",
        "| File | Rows | Columns | First date | Last date |",
        "|---|---:|---:|---|---|",
    ]
    for name, info in summary["files"].items():
        if info is None:
            lines.append(f"| {name} | — | — | missing | missing |")
        else:
            lines.append(
                f"| {name} | {info['rows']} | {info['columns']} | {info['first_date']} | {info['last_date']} |"
            )
    lines += [
        "",
        "Large moves and late listings are reported, not verified against corporate-action or",
        "news records. Prices are Yahoo auto-adjusted closes, so splits should already be",
        "adjusted; a split-like jump means the adjustment probably failed for that name.",
    ]
    decisions = settings.get("excluded_symbols") or {}
    if decisions:
        lines += ["", "## Recorded data decisions", ""]
        lines += [f"- **{symbol}** excluded: {reason}" for symbol, reason in decisions.items()]
    for severity in SEVERITIES:
        lines += ["", f"## {severity}", ""]
        rows = [f for f in shown if f.severity == severity]
        if not rows:
            lines.append("- None.")
        lines += [f"- `{f.check}` · {f.file}: {f.message}" for f in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--as-of", default=None,
                        help="Date for freshness checks (default: the last closed NYSE session in New York "
                             "time, which also flags rows dated after it as partial intraday bars; for "
                             "the research data/ with data_checks.research_snapshot_end set, the last "
                             "session before that end).")
    parser.add_argument("--write-report", action="store_true", help="Write the markdown report.")
    parser.add_argument("--update-manifest", action="store_true",
                        help="Record current SHA-256 hashes in the data manifest (review data first).")
    parser.add_argument("--strict", action="store_true", help="Exit 1 on WARNING as well as ERROR.")
    parser.add_argument("--paper", action="store_true",
                        help="Check the paper data dir (data/paper/ or $PAPER_DATA_DIR) instead of data/.")
    parser.add_argument("--paper-dir", default=None, help="Paper data dir override (implies --paper).")
    args = parser.parse_args(argv)

    data_paths = DataPaths.paper(args.paper_dir) if (args.paper or args.paper_dir) else None
    settings = data_check_settings()
    if data_paths is not None:
        settings = paper_manifest_settings(settings, data_paths)
        print(f"Checking paper data in {data_paths.root}/")
    if args.update_manifest:
        manifest = build_manifest(
            list(settings["manifest_files"]), decisions=settings.get("excluded_symbols") or None
        )
        Path(settings["manifest_path"]).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        print(f"Wrote {settings['manifest_path']} ({len(manifest['files'])} files)")

    findings, summary = run_data_checks(as_of=args.as_of, data_paths=data_paths)
    for f in findings:
        # INFO is silent except snapshot_lag, which is the live gap operators need
        # to see without opening (or dirtying) the committed report.
        if f.severity != "INFO" or f.check == "snapshot_lag":
            print(f"{f.severity:7s} {f.check:16s} {f.file}: {f.message}")
    info = summary["counts"]["INFO"]
    print(f"Data checks: {overall_status(findings)} "
          f"({summary['counts']['ERROR']} error, {summary['counts']['WARNING']} warning, {info} info)")
    if args.write_report:
        research = data_paths is None or getattr(data_paths, "kind", "research") == "research"
        path = Path(settings["report_path"])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_report(findings, summary, settings, checkout=research))
        print(f"Report saved to {path}")
        if research:
            local_path = Path(LOCAL_DATA_QUALITY_REPORT_PATH)
            local_path.parent.mkdir(parents=True, exist_ok=True)
            local_path.write_text(render_report(findings, summary, settings, checkout=False))
            print(f"Local report (includes last closed session) saved to {local_path}")
    status = overall_status(findings)
    if status == "ERROR" or (args.strict and status == "WARNING"):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
