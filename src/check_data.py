"""Check data freshness, alignment and quality; maintain the data manifest.

Read-only for data files. Examples:

    python src/check_data.py                       # print findings, exit 1 on ERROR
    python src/check_data.py --write-report        # also write reports/data_quality_report.md
    python src/check_data.py --as-of 2026-11-02    # evaluate freshness as of a date
    python src/check_data.py --update-manifest     # record current hashes (after review)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parents[1]))

from src.data.quality import (  # noqa: E402
    SEVERITIES,
    build_manifest,
    data_check_settings,
    overall_status,
    run_data_checks,
)


def render_report(findings, summary, settings) -> str:
    lines = [
        "# Data Quality Report",
        "",
        "Generated by `python src/check_data.py --write-report` (read-only; no data file is modified).",
        f"Freshness is evaluated as of **{summary['as_of']}**; re-run to refresh.",
        "",
        f"- Overall status: **{overall_status(findings)}**",
        f"- Findings: {summary['counts']['ERROR']} ERROR, {summary['counts']['WARNING']} WARNING, "
        f"{summary['counts']['INFO']} INFO",
        f"- Thresholds: stale > {settings['max_stale_trading_days']} trading days "
        f"({settings['stale_severity']}); date-range misalignment > {settings['max_end_date_gap_trading_days']} "
        f"trading days ({settings['misalignment_severity']}); calendar gap > {settings['max_calendar_gap_days']} "
        f"days; flat run ≥ {settings['flat_run_min_days']} identical closes; split-like jump ≥ "
        f"{settings['split_move_threshold']:.0%} with price ratio within {settings['split_ratio_tolerance']:.0%} "
        f"of a common split factor; large moves ≥ {settings['large_move_threshold']:.0%} listed as INFO.",
        "",
        "## Inputs",
        "",
        "| File | Rows | Columns | First date | Last date |",
        "|---|---:|---:|---|---|",
    ]
    for name, info in summary["files"].items():
        if info is None:
            lines.append(f"| {name} | — | — | missing | missing |")
        else:
            lines.append(
                f"| {name} | {info['rows']} | {info['columns']} | {info['first_date']} | {info['last_date']} |"
            )
    lines += [
        "",
        "Large moves and late listings are reported, not verified against corporate-action or",
        "news records. Prices are Yahoo auto-adjusted closes, so splits should already be",
        "adjusted; a split-like jump means the adjustment probably failed for that name.",
    ]
    decisions = settings.get("excluded_symbols") or {}
    if decisions:
        lines += ["", "## Recorded data decisions", ""]
        lines += [f"- **{symbol}** excluded: {reason}" for symbol, reason in decisions.items()]
    for severity in SEVERITIES:
        lines += ["", f"## {severity}", ""]
        rows = [f for f in findings if f.severity == severity]
        if not rows:
            lines.append("- None.")
        lines += [f"- `{f.check}` · {f.file}: {f.message}" for f in rows]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--as-of", default=None, help="Date for freshness checks (default: today).")
    parser.add_argument("--write-report", action="store_true", help="Write the markdown report.")
    parser.add_argument("--update-manifest", action="store_true",
                        help="Record current SHA-256 hashes in the data manifest (review data first).")
    parser.add_argument("--strict", action="store_true", help="Exit 1 on WARNING as well as ERROR.")
    args = parser.parse_args(argv)

    settings = data_check_settings()
    if args.update_manifest:
        manifest = build_manifest(
            list(settings["manifest_files"]), decisions=settings.get("excluded_symbols") or None
        )
        Path(settings["manifest_path"]).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
        print(f"Wrote {settings['manifest_path']} ({len(manifest['files'])} files)")

    findings, summary = run_data_checks(as_of=args.as_of)
    for f in findings:
        if f.severity != "INFO":
            print(f"{f.severity:7s} {f.check:16s} {f.file}: {f.message}")
    info = summary["counts"]["INFO"]
    print(f"Data checks: {overall_status(findings)} "
          f"({summary['counts']['ERROR']} error, {summary['counts']['WARNING']} warning, {info} info)")
    if args.write_report:
        path = Path(settings["report_path"])
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render_report(findings, summary, settings))
        print(f"Report saved to {path}")
    status = overall_status(findings)
    if status == "ERROR" or (args.strict and status == "WARNING"):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
